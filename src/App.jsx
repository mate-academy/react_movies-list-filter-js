import './App.scss';
import { useState } from 'react';
import { MoviesList } from './components/MoviesList';
import moviesFromServer from './api/movies.json';

export const App = () => {
  const [query, setQuery] = useState('');

  const normalSearch = query.trim().toLowerCase();

  const visibleMovies = moviesFromServer.filter(movie => {
    const normalTitle = movie.title.trim().toLowerCase();
    const normalDescription = movie.description.trim().toLowerCase();

    const isTitleMatch = normalTitle.includes(normalSearch);
    const isDescriptionMatch = normalDescription.includes(normalSearch);

    return isTitleMatch || isDescriptionMatch;
  });

  return (
    <div className="page">
      <div className="page-content">
        <div className="box">
          <div className="field">
            {/* eslint-disable-next-line jsx-a11y/label-has-associated-control */}
            <label htmlFor="search-query" className="label">
              Search movie
            </label>

            <div className="control">
              <input
                type="text"
                id="search-query"
                className="input"
                placeholder="Type search word"
                value={query}
                onChange={element => setQuery(element.target.value)}
              />
            </div>
          </div>
        </div>

        <MoviesList movies={visibleMovies} />
      </div>

      <div className="sidebar">Sidebar goes here</div>
    </div>
  );
};
